// --- demo tasks: each one prints a tag and the value of get_time() ---
void PrintTime(const char *tag)
{
    char buf[40];
    int n = sprintf(buf, "%s t=%lu ms\r\n", tag, (unsigned long)get_time());
    HAL_UART_Transmit(&huart1, (uint8_t *)buf, n, 10);
}

uint32_t id10ms;

void Task10ms(void)   { PrintTime("[10ms ]"); }
void Print500ms(void) { PrintTime("[500ms]"); }
void Print1s(void)    { PrintTime("[1s   ]"); }
void ShotA(void)      { PrintTime("[shot A]"); }
void ShotB(void)      { PrintTime("[shot B]"); }
void ShotC(void)      { PrintTime("[shot C]"); }
void Stop10ms(void)
{
    SCH_Delete_Task(id10ms);            // demonstrates SCH_Delete_Task
    PrintTime("[10ms stopped]");
}
